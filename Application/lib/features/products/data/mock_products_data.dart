  static List<Product> getProductsByCategory(String categoryId) {
    if (categoryId.isEmpty || categoryId == 'all') {
      return allProducts;
    }
    return allProducts.where((p) => p.categoryId == categoryId).toList();
  }

  static FreshCategory? getCategoryById(String categoryId) {
    try {
      return categories.firstWhere((c) => c.id == categoryId);
    } catch (_) {
      return null;
    }
  }
